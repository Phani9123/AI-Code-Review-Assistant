def _safe_json(value):
    """
    Convert a Python value into readable JSON for the LLM prompt.
    """
    try:
        return json.dumps(
            value,
            indent=2,
            ensure_ascii=False,
        )
    except (TypeError, ValueError):
        return "[]"


def _extract_ruff_issues(ruff_report):
    """
    Keep only useful Ruff information.
    """

    issues = []

    for issue in ruff_report.get("issues", []):

        if not isinstance(issue, dict):
            continue

        location = issue.get(
            "location",
            {},
        )

        if not isinstance(location, dict):
            location = {}

        issues.append(
            {
                "code": issue.get("code"),
                "message": issue.get("message"),
                "line": location.get("row"),
                "column": location.get("column"),
            }
        )

    return issues


def _extract_bandit_issues(bandit_report):
    """
    Keep only useful Bandit information.
    """

    issues = []

    for issue in bandit_report.get(
        "security_issues",
        [],
    ):

        if not isinstance(issue, dict):
            continue

        issues.append(
            {
                "test_id": issue.get("test_id"),
                "severity": issue.get("severity"),
                "confidence": issue.get("confidence"),
                "line": issue.get("line"),
                "problem": issue.get("problem"),
            }
        )

    return issues


def _extract_semantic_issues(semantic_report):
    """
    Keep only useful semantic-review findings.

    Semantic findings are generated by the LLM and therefore
    must be treated as evidence that needs to be considered,
    not blindly trusted.
    """

    if not isinstance(
        semantic_report,
        dict,
    ):
        return []

    issues = semantic_report.get(
        "issues",
        [],
    )

    if not isinstance(
        issues,
        list,
    ):
        return []

    normalized = []

    for issue in issues:

        if not isinstance(
            issue,
            dict,
        ):
            continue

        normalized.append(
            {
                "category": issue.get(
                    "category"
                ),
                "severity": issue.get(
                    "severity"
                ),
                "confidence": issue.get(
                    "confidence"
                ),
                "line": issue.get(
                    "line"
                ),
                "end_line": issue.get(
                    "end_line"
                ),
                "problem": issue.get(
                    "problem"
                ),
                "evidence": issue.get(
                    "evidence"
                ),
                "why": issue.get(
                    "why"
                ),
                "verification": issue.get(
                    "verification"
                ),
                "change": issue.get(
                    "change"
                ),
            }
        )

    return normalized


