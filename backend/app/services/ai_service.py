def generate_complete_fix(
    source_code,
    bandit_report,
    ruff_report,
    semantic_report=None,
):
    """
    Generate one complete corrected Python program.

    The AI receives:

        Original source
        +
        Bandit findings
        +
        Ruff findings
        +
        Semantic findings

    This function does NOT automatically trust the generated
    code. The caller must run AI safety and final validation.
    """

    prompt = build_complete_fix_prompt(
        source_code=source_code,
        bandit_report=bandit_report,
        ruff_report=ruff_report,
        semantic_report=semantic_report,
    )

    try:

        print(
            "\n========== COMPLETE AI FIX REQUEST =========="
        )

        response = requests.post(
            OLLAMA_URL,
            json={
                "model": MODEL_NAME,
                "prompt": prompt,
                "stream": False,
                "format": "json",
                "options": {
                    "temperature": 0,
                    "num_predict": 3000,
                },
            },
            timeout=180,
        )

        response.raise_for_status()

        data = response.json()

        ai_response = data.get(
            "response",
            "",
        ).strip()

        if not ai_response:

            print(
                "\n⚠️ AI returned an empty response."
            )

            return {
                "summary": (
                    "The AI returned an empty response."
                ),
                "fix": (
                    "No corrected code was generated."
                ),
                "corrected_code": "",
                "manual_review_required": True,
            }

        print(
            "\n========== RAW COMPLETE AI RESPONSE =========="
        )

        print(ai_response)

        parsed = parse_ai_json(
            ai_response
        )

        if not isinstance(
            parsed,
            dict,
        ):

            print(
                "\n⚠️ AI response could not be parsed."
            )

            return {
                "summary": (
                    "The AI returned an invalid response."
                ),
                "fix": (
                    "The complete AI fix could not be parsed."
                ),
                "corrected_code": "",
                "manual_review_required": True,
            }

        corrected_code = parsed.get(
            "corrected_code",
            "",
        )

        if corrected_code is None:
            corrected_code = ""

        corrected_code = str(
            corrected_code
        )

        summary = str(
            parsed.get(
                "summary",
                "",
            )
        )

        fix = str(
            parsed.get(
                "fix",
                "",
            )
        )

        manual_review_required = parsed.get(
            "manual_review_required",
            False,
        )

        if not isinstance(
            manual_review_required,
            bool,
        ):
            manual_review_required = False

        # ----------------------------------------------------
        # If the AI explicitly requires manual review,
        # do not override it.
        # ----------------------------------------------------

        if manual_review_required:

            return {
                "summary": (
                    summary
                    or "Manual review is required."
                ),
                "fix": (
                    fix
                    or (
                        "The AI could not safely "
                        "determine the intended behavior."
                    )
                ),
                "corrected_code": "",
                "manual_review_required": True,
            }

        # ----------------------------------------------------
        # Empty corrected code
        # ----------------------------------------------------

        if not corrected_code.strip():

            return {
                "summary": (
                    summary
                    or "No corrected code was generated."
                ),
                "fix": (
                    fix
                    or (
                        "The AI did not provide "
                        "corrected code."
                    )
                ),
                "corrected_code": "",
                "manual_review_required": True,
            }

        return {
            "summary": summary,
            "fix": fix,
            "corrected_code": corrected_code,
            "manual_review_required": False,
        }

    except requests.exceptions.Timeout:

        print(
            "\n⚠️ Complete AI fix request timed out."
        )

        return {
            "summary": (
                "The AI fix request timed out."
            ),
            "fix": (
                "The local LLM did not complete "
                "the correction within the allowed time."
            ),
            "corrected_code": "",
            "manual_review_required": True,
        }

    except requests.exceptions.ConnectionError:

        print(
            "\n⚠️ Could not connect to Ollama."
        )

        return {
            "summary": (
                "Could not connect to the local AI model."
            ),
            "fix": (
                "Make sure Ollama is running and "
                "the configured model is available."
            ),
            "corrected_code": "",
            "manual_review_required": True,
        }

    except requests.exceptions.RequestException as e:

        print(
            f"\n⚠️ Complete AI fix request failed: {e}"
        )

        return {
            "summary": (
                "The AI fix request failed."
            ),
            "fix": (
                "The local AI service returned "
                "a request error."
            ),
            "corrected_code": "",
            "manual_review_required": True,
        }

    except Exception as e:

        print(
            f"\n⚠️ Unexpected AI fix error: {e}"
        )

        return {
            "summary": (
                "An unexpected error occurred "
                "while generating the AI fix."
            ),
            "fix": (
                "The correction could not be safely generated."
            ),
            "corrected_code": "",
            "manual_review_required": True,
        }


