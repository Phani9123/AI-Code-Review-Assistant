# F821 AMBIGUITY DETECTION
# ============================================================

KNOWN_SAFE_TYPO_REPLACEMENTS = {
    "rang": "range",
    "lenght": "length",
    "pritn": "print",
    "prnit": "print",
    "strng": "string",
}


def has_ambiguous_ruff_issues(
    ruff_report,
):
    """
    Determine whether Ruff contains an F821 issue that cannot
    be safely resolved.

    Known obvious typos such as:

        rang -> range

    are considered safe.

    Unknown undefined identifiers such as:

        total

    remain ambiguous.

    IMPORTANT:

    This function does NOT mean the entire AI review must stop.

    It only informs the caller that an F821 issue needs special
    attention.
    """

    print(
        "\n========== F821 AMBIGUITY CHECK =========="
    )

    for issue in ruff_report.get(
        "issues",
        [],
    ):

        if not isinstance(
            issue,
            dict,
        ):
            continue

        code = issue.get(
            "code"
        )

        if code != "F821":
            continue

        message = str(
            issue.get(
                "message",
                "",
            )
        )

        print(
            f"F821 message: {message}"
        )

        # ----------------------------------------------------
        # Ruff normally produces:
        #
        # Undefined name `total`
        #
        # or:
        #
        # Undefined name 'total'
        # ----------------------------------------------------

        match = re.search(
            r"Undefined name [`']([^`']+)[`']",
            message,
        )

        if not match:

            print(
                "Could not determine undefined identifier."
            )

            return True

        name = match.group(1)

        # ----------------------------------------------------
        # Known safe typo
        # ----------------------------------------------------

        if name in KNOWN_SAFE_TYPO_REPLACEMENTS:

            replacement = (
                KNOWN_SAFE_TYPO_REPLACEMENTS[
                    name
                ]
            )

            print(
                f"Detected known typo: "
                f"{name} -> {replacement}"
            )

            continue

        # ----------------------------------------------------
        # Unknown identifier
        # ----------------------------------------------------

        print(
            f"Unknown undefined name: {name}"
        )

        print(
            "The AI must determine whether this can be "
            "safely resolved."
        )

        return True

    return False