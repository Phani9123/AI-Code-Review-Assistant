def build_bandit_explanation_prompt(
    bandit_report,
    source_code,
):
    """
    Build a prompt for explaining Bandit findings.

    This does NOT generate the complete corrected program.
    """

    issues = _extract_bandit_issues(
        bandit_report
    )

    return f"""
You are a senior Python security engineer.

Explain the Bandit findings below using ONLY the original
source code.

Do not invent behavior.

For every finding explain:

- what is wrong
- why it matters
- how it should be fixed
- the relevant source-code behavior

If the finding is not actually applicable to the source,
say so rather than inventing a problem.

Return ONLY valid JSON.

Required structure:

{{
    "security_issues": [
        {{
            "test_id": "...",
            "severity": "...",
            "confidence": "...",
            "line": 1,
            "problem": "...",
            "why": "...",
            "fix": "..."
        }}
    ]
}}

ORIGINAL SOURCE:

{source_code}

BANDIT FINDINGS:

{_safe_json(issues)}
"""


def explain_bandit_report(
    bandit_report,
    source_code,
):
    """
    Add AI explanations to Bandit findings.
    """

    issues = _extract_bandit_issues(
        bandit_report
    )

    if not issues:
        return bandit_report

    prompt = build_bandit_explanation_prompt(
        bandit_report,
        source_code,
    )

    try:

        response = requests.post(
            OLLAMA_URL,
            json={
                "model": MODEL_NAME,
                "prompt": prompt,
                "stream": False,
                "format": "json",
                "options": {
                    "temperature": 0,
                    "num_predict": 1200,
                },
            },
            timeout=120,
        )

        response.raise_for_status()

        data = response.json()

        ai_response = data.get(
            "response",
            "",
        ).strip()

        if not ai_response:
            return bandit_report

        parsed = parse_ai_json(
            ai_response
        )

        if not isinstance(
            parsed,
            dict,
        ):
            return bandit_report

        explanations = parsed.get(
            "security_issues",
            [],
        )

        if not isinstance(
            explanations,
            list,
        ):
            return bandit_report

        # Match explanations back to Bandit issues.
        for index, issue in enumerate(
            bandit_report.get(
                "security_issues",
                [],
            )
        ):

            if index >= len(
                explanations
            ):
                break

            explanation = explanations[
                index
            ]

            if not isinstance(
                explanation,
                dict,
            ):
                continue

            issue["why"] = explanation.get(
                "why",
                issue.get("why", ""),
            )

            issue["fix"] = explanation.get(
                "fix",
                issue.get("fix", ""),
            )

        return bandit_report

    except (
        requests.exceptions.RequestException,
        ValueError,
        TypeError,
    ):

        return bandit_report


